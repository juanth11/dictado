/// Un elemento del historial del portapapeles.
struct Recorte: Codable, Identifiable, Equatable {
    enum Tipo: String, Codable { case texto, enlace, imagen, archivo }

    let id: UUID
    var tipo: Tipo
    var texto: String        // texto plano, URL o rutas de archivo (una por línea)
    var fecha: Date
    var app: String?         // app de origen
    var appID: String?
    var origen: String?      // página web de origen (Arc, Chrome)
    var fijado = false
    var conFormato = false   // hay HTML/RTF guardado aparte
    var ancho: Int?
    var alto: Int?

    var titulo: String {
        switch tipo {
        case .imagen:
            return "Imagen \(ancho ?? 0) × \(alto ?? 0)"
        case .archivo:
            let rutas = texto.split(separator: "\n")
            let nombre = rutas.first.map { URL(fileURLWithPath: String($0)).lastPathComponent } ?? texto
            return rutas.count > 1 ? "\(nombre) y \(rutas.count - 1) más" : nombre
        case .texto, .enlace:
            let linea = texto.split(whereSeparator: \.isNewline).first.map(String.init) ?? texto
            return linea.trimmingCharacters(in: .whitespaces)
        }
    }

    var simbolo: String {
        switch tipo {
        case .texto: return "text.alignleft"
        case .enlace: return "link"
        case .imagen: return "photo"
        case .archivo: return "doc"
        }
    }
}

/// Historial del portapapeles: vigila los cambios, filtra lo privado y lo guarda en disco (FileVault lo cifra).
@MainActor @Observable
final class Historial {
    private(set) var recortes: [Recorte] = []

    @ObservationIgnored private let pb: NSPasteboard
    @ObservationIgnored private let carpeta: URL?
    @ObservationIgnored private var conteo: Int
    @ObservationIgnored private var temporizador: Timer?
    @ObservationIgnored private var pausaHasta: Date?
    @ObservationIgnored private var imagenes: [UUID: NSImage] = [:]
    @ObservationIgnored private var miniaturas: [UUID: NSImage] = [:]

    /// Marca lo que escribe Dictado, para no volver a capturarlo.
    static let marca = NSPasteboard.PasteboardType("app.dictado.propio")
    private static let tiposPrivados: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    private static let appsPrivadas: Set<String> = [
        "com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password",
        "com.agilebits.onepassword7", "com.bitwarden.desktop",
    ]
    static let limite = 500
    static let dias = 30.0

    init(carpeta: URL, pasteboard: NSPasteboard = .general) {
        pb = pasteboard
        self.carpeta = carpeta
        conteo = pasteboard.changeCount
        try? FileManager.default.createDirectory(at: carpeta, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        var url = carpeta
        var valores = URLResourceValues()
        valores.isExcludedFromBackup = true  // fuera de Time Machine
        try? url.setResourceValues(valores)
        cargar()
    }

    /// Historial en memoria para vistas previas.
    init(muestra: [Recorte]) {
        pb = NSPasteboard(name: NSPasteboard.Name("app.dictado.muestra"))
        carpeta = nil
        conteo = 0
        recortes = muestra
    }

    func vigilar() {
        temporizador = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.revisar() }
        }
    }

    // MARK: Captura

    /// Pausa la captura mientras un módulo usa el portapapeles de paso (⌘C simulado para leer una selección,
    /// pegar un resultado y devolver lo que había): lo que cambie durante la pausa no entra al historial.
    /// Se reanuda sola a los 5 s por si quien pausó nunca reanuda.
    func pausar(_ si: Bool) {
        conteo = pb.changeCount
        pausaHasta = si ? Date().addingTimeInterval(5) : nil
    }

    func revisar(app: NSRunningApplication? = NSWorkspace.shared.frontmostApplication) {
        guard pb.changeCount != conteo else { return }
        conteo = pb.changeCount
        if let pausaHasta, Date() < pausaHasta { return }
        let tipos = Set((pb.types ?? []).map(\.rawValue))
        guard !tipos.contains(Self.marca.rawValue), tipos.isDisjoint(with: Self.tiposPrivados) else { return }
        if let id = app?.bundleIdentifier, Self.appsPrivadas.contains(id) { return }

        var r = Recorte(id: UUID(), tipo: .texto, texto: "", fecha: Date(), app: app?.localizedName, appID: app?.bundleIdentifier)
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            r.tipo = .archivo
            r.texto = urls.map(\.path).joined(separator: "\n")
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            r.texto = s
            r.tipo = Self.esEnlace(s) ? .enlace : .texto
            r.origen = pb.string(forType: NSPasteboard.PasteboardType("org.chromium.source-url"))
            if let html = pb.data(forType: .html) {
                escribirArchivo(html, r.id, "html")
                r.conFormato = true
            } else if let rtf = pb.data(forType: .rtf) {
                escribirArchivo(rtf, r.id, "rtf")
                r.conFormato = true
            }
        } else if let imagen = NSImage(pasteboard: pb), let rep = imagen.representations.first,
                  let png = NSBitmapImageRep(data: imagen.tiffRepresentation ?? Data())?.representation(using: .png, properties: [:]) {
            r.tipo = .imagen
            r.ancho = rep.pixelsWide
            r.alto = rep.pixelsHigh
            escribirArchivo(png, r.id, "png")
        } else {
            return
        }
        // Copiar lo mismo otra vez lo sube arriba en vez de duplicarlo.
        if r.tipo != .imagen, let i = recortes.firstIndex(where: { $0.tipo == r.tipo && $0.texto == r.texto }) {
            r.fijado = recortes[i].fijado
            borrarArchivos(recortes.remove(at: i))
        }
        recortes.insert(r, at: 0)
        podar()
        persistir()
    }

    static func esEnlace(_ s: String) -> Bool {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(where: \.isWhitespace), let url = URL(string: t), let esquema = url.scheme?.lowercased() else { return false }
        return ["http", "https", "mailto", "ftp"].contains(esquema)
    }

    // MARK: Acciones

    /// Vuelve a poner el recorte en el portapapeles (y lo sube al tope del historial).
    func escribir(_ r: Recorte, conFormato: Bool = true) {
        pb.clearContents()
        switch r.tipo {
        case .texto, .enlace:
            let item = NSPasteboardItem()
            item.setString(r.texto, forType: .string)
            if conFormato, r.conFormato {
                if let html = leerArchivo(r.id, "html") {
                    item.setData(html, forType: .html)
                } else if let rtf = leerArchivo(r.id, "rtf") {
                    item.setData(rtf, forType: .rtf)
                }
            }
            item.setString("1", forType: Self.marca)
            pb.writeObjects([item])
        case .imagen:
            if let imagen = imagen(de: r) { pb.writeObjects([imagen]) }
            pb.addTypes([Self.marca], owner: nil)
            pb.setString("1", forType: Self.marca)
        case .archivo:
            let urls = r.texto.split(separator: "\n").map { NSURL(fileURLWithPath: String($0)) }
            pb.writeObjects(urls)
            pb.addTypes([Self.marca], owner: nil)
            pb.setString("1", forType: Self.marca)
        }
        conteo = pb.changeCount
        if let i = recortes.firstIndex(where: { $0.id == r.id }) {
            var subido = recortes.remove(at: i)
            subido.fecha = Date()
            recortes.insert(subido, at: 0)
            persistir()
        }
    }

    func alternarFijado(_ id: UUID) {
        guard let i = recortes.firstIndex(where: { $0.id == id }) else { return }
        recortes[i].fijado.toggle()
        persistir()
    }

    func borrar(_ id: UUID) {
        guard let i = recortes.firstIndex(where: { $0.id == id }) else { return }
        borrarArchivos(recortes.remove(at: i))
        persistir()
    }

    func imagen(de r: Recorte) -> NSImage? {
        if let cache = imagenes[r.id] { return cache }
        guard let datos = leerArchivo(r.id, "png"), let img = NSImage(data: datos) else { return nil }
        imagenes[r.id] = img
        return img
    }

    /// Escribe varios recortes a la vez: imágenes y archivos como elementos separados, textos unidos.
    func escribir(varios rs: [Recorte], conFormato: Bool = true, limpio: Bool = false) {
        if rs.count == 1, !limpio {
            escribir(rs[0], conFormato: conFormato)
            return
        }
        pb.clearContents()
        var objetos: [NSPasteboardWriting] = []
        let textos = rs.filter { $0.tipo == .texto || $0.tipo == .enlace }.map { limpio ? Limpieza.aplicar($0.texto) : $0.texto }
        if !textos.isEmpty {
            let item = NSPasteboardItem()
            item.setString(textos.joined(separator: "\n\n"), forType: .string)
            item.setString("1", forType: Self.marca)
            objetos.append(item)
        }
        for r in rs where r.tipo == .imagen {
            guard let datos = leerArchivo(r.id, "png") else { continue }
            let item = NSPasteboardItem()
            item.setData(datos, forType: .png)
            if let tiff = NSImage(data: datos)?.tiffRepresentation { item.setData(tiff, forType: .tiff) }
            item.setString("1", forType: Self.marca)
            objetos.append(item)
        }
        for r in rs where r.tipo == .archivo {
            objetos += r.texto.split(separator: "\n").map { NSURL(fileURLWithPath: String($0)) }
        }
        pb.writeObjects(objetos)
        conteo = pb.changeCount
    }

    /// Lo que se arrastra a otra app: imágenes y archivos como archivos, textos como texto, enlaces como URL.
    func objetosArrastre(_ rs: [Recorte]) -> [NSPasteboardWriting] {
        rs.flatMap { r -> [NSPasteboardWriting] in
            switch r.tipo {
            case .texto:
                return [r.texto as NSString]
            case .enlace:
                if let url = URL(string: r.texto.trimmingCharacters(in: .whitespacesAndNewlines)) { return [url as NSURL] }
                return [r.texto as NSString]
            case .imagen:
                return archivo(r.id, "png").map { [$0 as NSURL] } ?? []
            case .archivo:
                return r.texto.split(separator: "\n").map { NSURL(fileURLWithPath: String($0)) }
            }
        }
    }

    /// Miniatura liviana (máx. 240 px) sin cargar la imagen completa en memoria.
    func miniatura(de r: Recorte) -> NSImage? {
        if let m = miniaturas[r.id] { return m }
        guard r.tipo == .imagen, let url = archivo(r.id, "png"),
              let fuente = CGImageSourceCreateWithURL(url as CFURL, nil),
              let cg = CGImageSourceCreateThumbnailAtIndex(fuente, 0, [
                  kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: 240,
              ] as CFDictionary) else { return nil }
        let m = NSImage(cgImage: cg, size: NSSize(width: cg.width / 2, height: cg.height / 2))
        miniaturas[r.id] = m
        return m
    }

    func fijar(_ ids: [UUID], _ valor: Bool) {
        for i in recortes.indices where ids.contains(recortes[i].id) { recortes[i].fijado = valor }
        persistir()
    }

    func borrar(_ ids: Set<UUID>) {
        let quitados = recortes.filter { ids.contains($0.id) }
        recortes.removeAll { ids.contains($0.id) }
        quitados.forEach(borrarArchivos)
        persistir()
    }

    // MARK: Disco

    private var indice: URL? { carpeta?.appendingPathComponent("historial.json") }

    private func cargar() {
        guard let indice, let datos = try? Data(contentsOf: indice) else { return }
        let dec = JSONDecoder()
        dec.dateDecodingStrategy = .iso8601
        recortes = (try? dec.decode([Recorte].self, from: datos)) ?? []
        podar()
    }

    private func persistir() {
        guard let indice else { return }
        let enc = JSONEncoder()
        enc.dateEncodingStrategy = .iso8601
        guard let datos = try? enc.encode(recortes) else { return }
        do {
            try datos.write(to: indice, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: indice.path)
        } catch {
            log.error("no pude guardar el historial: \(error.localizedDescription, privacy: .public)")
        }
    }

    /// Quita lo no fijado de más de 30 días y deja máximo 500 recortes sin fijar.
    private func podar() {
        let corte = Date().addingTimeInterval(-Self.dias * 86_400)
        var sinFijar = 0
        recortes.removeAll { r in
            guard !r.fijado else { return false }
            sinFijar += 1
            let sobra = r.fecha < corte || sinFijar > Self.limite
            if sobra { borrarArchivos(r) }
            return sobra
        }
    }

    private func archivo(_ id: UUID, _ ext: String) -> URL? {
        carpeta?.appendingPathComponent("\(id.uuidString).\(ext)")
    }

    private func escribirArchivo(_ datos: Data, _ id: UUID, _ ext: String) {
        guard let url = archivo(id, ext) else { return }
        try? datos.write(to: url, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }

    private func leerArchivo(_ id: UUID, _ ext: String) -> Data? {
        archivo(id, ext).flatMap { try? Data(contentsOf: $0) }
    }

    private func borrarArchivos(_ r: Recorte) {
        imagenes[r.id] = nil
        miniaturas[r.id] = nil
        for ext in ["png", "html", "rtf"] {
            if let url = archivo(r.id, ext) { try? FileManager.default.removeItem(at: url) }
        }
    }
}

// MARK: - Panel

/// Panel que recibe el teclado sin activar la app: la app donde estabas sigue al frente para pegar.
final class PanelClave: NSPanel {
    override var canBecomeKey: Bool { true }
    override var canBecomeMain: Bool { false }
}

@MainActor @Observable
final class EstadoPanel {
    enum Filtro: String, CaseIterable {
        case todo = "Todo", texto = "Texto", enlaces = "Enlaces", imagenes = "Imágenes", archivos = "Archivos", fijados = "Fijados"
    }

    var busqueda = ""
    var filtro = Filtro.todo
    var seleccion: UUID?     // el cursor
    var marcados: Set<UUID> = []  // selección múltiple (⌘clic, ⇧clic, ⇧↑↓, ⌘A)
    var ancla: UUID?         // desde dónde se extiende un rango
    var appDestino = ""
}

/// Texto copiado de un PDF: une líneas cortadas, quita guiones de corte y espacios dobles; respeta párrafos.
enum Limpieza {
    static func aplicar(_ s: String) -> String {
        var t = s.replacingOccurrences(of: "\r\n", with: "\n")
        t = t.replacingOccurrences(of: #"(\p{Ll})-\n(\p{Ll})"#, with: "$1$2", options: .regularExpression)
        t = t.replacingOccurrences(of: #"\n[ \t]*\n+"#, with: "\u{2029}", options: .regularExpression)
        t = t.replacingOccurrences(of: "\n", with: " ")
        t = t.replacingOccurrences(of: "\u{2029}", with: "\n\n")
        t = t.replacingOccurrences(of: #"[ \t]{2,}"#, with: " ", options: .regularExpression)
        return t.trimmingCharacters(in: .whitespacesAndNewlines)
    }
}

/// ⌘⌥V: abre el historial; ↩ pega en la app donde estabas. ⌘clic / ⇧clic / ⌘A seleccionan varios.
@MainActor
final class Portapapeles {
    let historial: Historial
    let estado = EstadoPanel()
    var alGuardarEnInbox: ((String) -> Void)?
    private let panel: PanelClave
    private var monitor: Any?

    init(historial: Historial) {
        self.historial = historial
        panel = PanelClave(contentRect: NSRect(x: 0, y: 0, width: VistaPortapapeles.ancho, height: VistaPortapapeles.alto),
                           styleMask: [.borderless, .nonactivatingPanel, .fullSizeContentView], backing: .buffered, defer: true)
        panel.isFloatingPanel = true
        panel.level = .floating
        panel.backgroundColor = .clear
        panel.isOpaque = false
        panel.hasShadow = true
        panel.hidesOnDeactivate = false
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
        panel.contentView = NSHostingView(rootView: VistaPortapapeles(historial: historial, estado: estado, control: self))
        NotificationCenter.default.addObserver(forName: NSWindow.didResignKeyNotification, object: panel, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.cerrar() }
        }
    }

    var abierto: Bool { panel.isVisible }

    func alternar() { abierto ? cerrar() : abrir() }

    func abrir() {
        estado.appDestino = NSWorkspace.shared.frontmostApplication?.localizedName ?? "la app"
        estado.busqueda = ""
        estado.filtro = .todo
        estado.marcados = []
        estado.seleccion = visibles().first?.id
        estado.ancla = estado.seleccion
        if let pantalla = NSScreen.main {
            let z = pantalla.visibleFrame
            panel.setFrameOrigin(NSPoint(x: z.midX - VistaPortapapeles.ancho / 2, y: z.midY - VistaPortapapeles.alto / 2 + z.height * 0.06))
        }
        panel.makeKeyAndOrderFront(nil)
        if monitor == nil {
            monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] evento in
                nonisolated(unsafe) let e = evento  // el monitor local siempre corre en el hilo principal
                return MainActor.assumeIsolated { self?.tecla(e) ?? e }
            }
        }
    }

    func cerrar() {
        guard abierto else { return }
        panel.orderOut(nil)
        if let monitor { NSEvent.removeMonitor(monitor) }
        monitor = nil
    }

    func visibles() -> [Recorte] {
        Self.filtrar(historial.recortes, estado)
    }

    static func filtrar(_ recortes: [Recorte], _ estado: EstadoPanel) -> [Recorte] {
        let normalizar = { (s: String) in s.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: .current) }
        let consulta = normalizar(estado.busqueda.trimmingCharacters(in: .whitespaces))
        return recortes
            .filter { r in
                switch estado.filtro {
                case .todo: return true
                case .texto: return r.tipo == .texto
                case .enlaces: return r.tipo == .enlace
                case .imagenes: return r.tipo == .imagen
                case .archivos: return r.tipo == .archivo
                case .fijados: return r.fijado
                }
            }
            .filter { consulta.isEmpty || normalizar($0.texto + " " + ($0.app ?? "") + " " + ($0.origen ?? "")).contains(consulta) }
            .sorted { ($0.fijado ? 1 : 0, $0.fecha) > ($1.fijado ? 1 : 0, $1.fecha) }
    }

    var seleccionado: Recorte? {
        historial.recortes.first { $0.id == estado.seleccion }
    }

    /// La selección efectiva: los marcados (en el orden de la lista) o el elemento del cursor.
    func seleccionados() -> [Recorte] {
        Self.elegidos(visibles(), estado, seleccionado)
    }

    static func elegidos(_ lista: [Recorte], _ estado: EstadoPanel, _ actual: Recorte?) -> [Recorte] {
        if estado.marcados.count > 1 { return lista.filter { estado.marcados.contains($0.id) } }
        return actual.map { [$0] } ?? []
    }

    // MARK: Selección

    func clic(_ id: UUID, modificadores: NSEvent.ModifierFlags, clics: Int) {
        if clics >= 2 {
            if !estado.marcados.contains(id) { estado.marcados = [] }
            estado.seleccion = id
            pegar()
            return
        }
        if modificadores.contains(.command) {
            if estado.marcados.isEmpty, let actual = estado.seleccion { estado.marcados = [actual] }
            if estado.marcados.contains(id) { estado.marcados.remove(id) } else { estado.marcados.insert(id) }
            estado.seleccion = id
            estado.ancla = id
        } else if modificadores.contains(.shift) {
            estado.seleccion = id
            marcarRango()
        } else {
            estado.marcados = []
            estado.seleccion = id
            estado.ancla = id
        }
    }

    func mover(_ paso: Int, extender: Bool = false) {
        let lista = visibles()
        guard !lista.isEmpty else { return }
        let i = lista.firstIndex { $0.id == estado.seleccion } ?? -paso
        let nuevo = lista[min(max(i + paso, 0), lista.count - 1)].id
        estado.seleccion = nuevo
        if extender {
            marcarRango()
        } else {
            estado.marcados = []
            estado.ancla = nuevo
        }
    }

    private func marcarRango() {
        let ids = visibles().map(\.id)
        guard let actual = estado.seleccion, let b = ids.firstIndex(of: actual) else { return }
        let a = estado.ancla.flatMap { ids.firstIndex(of: $0) } ?? b
        estado.marcados = Set(ids[min(a, b)...max(a, b)])
    }

    func seleccionarTodo() {
        estado.marcados = Set(visibles().map(\.id))
    }

    func ciclarFiltro(_ paso: Int) {
        let todos = EstadoPanel.Filtro.allCases
        let i = todos.firstIndex(of: estado.filtro) ?? 0
        estado.filtro = todos[(i + paso + todos.count) % todos.count]
        estado.marcados = []
        estado.seleccion = visibles().first?.id
        estado.ancla = estado.seleccion
    }

    // MARK: Acciones

    /// ↩ pega la selección (⇧↩ sin formato, ⌥↩ limpio). Varias imágenes llegan como varias imágenes.
    func pegar(conFormato: Bool = true, limpio: Bool = false) {
        let rs = seleccionados()
        guard !rs.isEmpty else { return }
        historial.escribir(varios: rs, conFormato: conFormato, limpio: limpio)
        cerrar()
        Task {
            try? await Task.sleep(for: .milliseconds(90))  // que la app de destino recupere el foco
            await Salida.simularPegar()
        }
    }

    func pegarNumero(_ n: Int) {
        let lista = visibles()
        guard n < lista.count else { return }
        estado.marcados = []
        estado.seleccion = lista[n].id
        pegar()
    }

    func copiar() {
        let rs = seleccionados()
        guard !rs.isEmpty else { return }
        historial.escribir(varios: rs)
        cerrar()
    }

    func fijar() {
        let rs = seleccionados()
        historial.fijar(rs.map(\.id), rs.contains { !$0.fijado })
    }

    func borrar() {
        let rs = seleccionados()
        guard let primero = rs.first else { return }
        let i = visibles().firstIndex { $0.id == primero.id } ?? 0
        historial.borrar(Set(rs.map(\.id)))
        estado.marcados = []
        let resto = visibles()
        estado.seleccion = resto.isEmpty ? nil : resto[min(i, resto.count - 1)].id
        estado.ancla = estado.seleccion
    }

    func aInbox() {
        let textos = seleccionados().filter { $0.tipo == .texto || $0.tipo == .enlace }.map(\.texto)
        guard !textos.isEmpty else { return }
        cerrar()
        alGuardarEnInbox?(textos.joined(separator: "\n\n"))
    }

    func abrirSeleccion() {
        var archivos: [URL] = []
        for r in seleccionados() {
            switch r.tipo {
            case .enlace:
                if let url = URL(string: r.texto.trimmingCharacters(in: .whitespacesAndNewlines)) { NSWorkspace.shared.open(url) }
            case .archivo:
                archivos += r.texto.split(separator: "\n").map { URL(fileURLWithPath: String($0)) }
            default:
                continue
            }
        }
        if !archivos.isEmpty { NSWorkspace.shared.activateFileViewerSelecting(archivos) }
        cerrar()
    }

    /// Arrastrar un elemento marcado lleva toda la selección; uno sin marcar, solo ese.
    func arrastre(desde id: UUID) -> (objetos: [NSPasteboardWriting], imagen: NSImage?) {
        let lista = visibles()
        let rs = estado.marcados.count > 1 && estado.marcados.contains(id)
            ? lista.filter { estado.marcados.contains($0.id) }
            : lista.filter { $0.id == id }
        let primero = rs.first
        let imagen = primero.flatMap { historial.miniatura(de: $0) }
            ?? NSImage(systemSymbolName: primero?.simbolo ?? "doc.on.clipboard", accessibilityDescription: nil)
        return (historial.objetosArrastre(rs), imagen)
    }

    private func tecla(_ evento: NSEvent) -> NSEvent? {
        guard panel.isKeyWindow else { return evento }
        let cmd = evento.modifierFlags.contains(.command)
        let shift = evento.modifierFlags.contains(.shift)
        let opcion = evento.modifierFlags.contains(.option)
        let rejilla = estado.filtro == .imagenes
        switch Int(evento.keyCode) {
        case kVK_Escape:
            if estado.marcados.count > 1 { estado.marcados = [] } else { cerrar() }
            return nil
        case kVK_UpArrow: mover(rejilla ? -2 : -1, extender: shift); return nil
        case kVK_DownArrow: mover(rejilla ? 2 : 1, extender: shift); return nil
        case kVK_LeftArrow where rejilla: mover(-1, extender: shift); return nil
        case kVK_RightArrow where rejilla: mover(1, extender: shift); return nil
        case kVK_Tab: ciclarFiltro(shift ? -1 : 1); return nil
        case kVK_Return, kVK_ANSI_KeypadEnter:
            pegar(conFormato: !shift, limpio: opcion)
            return nil
        case kVK_Delete where cmd: borrar(); return nil
        default: break
        }
        guard cmd, let letra = evento.charactersIgnoringModifiers?.lowercased() else { return evento }
        switch letra {
        case "a": seleccionarTodo(); return nil
        case "c": copiar(); return nil
        case "p": fijar(); return nil
        case "i": aInbox(); return nil
        case "o": abrirSeleccion(); return nil
        default:
            if let n = Int(letra), (1...9).contains(n) {
                pegarNumero(n - 1)
                return nil
            }
            return evento
        }
    }
